#!/usr/bin/env node
/**
 * Extract SVG path data from @phosphor-icons/core
 *
 * Usage: node scripts/extract-icon-paths.js
 *
 * This script reads SVG files from @phosphor-icons/core and extracts
 * the path data for use in canvas rendering (avoiding React overhead).
 */

import { readFileSync, readdirSync } from 'fs';
import { join, dirname } from 'path';
