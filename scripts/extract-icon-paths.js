function toPascalCase(str) {
  return str
    .split('-')
    .map(word => word.charAt(0).toUpperCase() + word.slice(1))
    .join('');
}

function extractPathFromSvg(svgContent) {
  // Match all path d attributes and combine them
  const matches = [...svgContent.matchAll(/d="([^"]+)"/g)];
  if (matches.length === 0) return null;

  // Most icons have a single path, but some have multiple
  // We'll join them with a space if there are multiple
  return matches.map(m => m[1]).join(' ');
}

function main() {
  const iconPaths = {};
  const errors = [];

  for (const iconName of ICONS_TO_EXTRACT) {
    const filePath = join(ICONS_DIR, `${iconName}.svg`);
    try {
      const svgContent = readFileSync(filePath, 'utf-8');
      const pathData = extractPathFromSvg(svgContent);

      if (pathData) {
        const key = toPascalCase(iconName);
        iconPaths[key] = pathData;
      } else {
        errors.push(`No path found in ${iconName}.svg`);
      }
    } catch (err) {
      errors.push(`Failed to read ${iconName}.svg: ${err.message}`);
    }
  }

  // Output the result
  console.log('// Auto-generated by scripts/extract-icon-paths.js');
  console.log('// Run: npm run extract-icons');
  console.log('// SVG path data for icons - extracted from Phosphor Icons (regular weight)');
  console.log('// This allows us to draw directly to canvas without React component overhead');
  console.log('const ICON_PATHS = {');

  const entries = Object.entries(iconPaths);
  entries.forEach(([key, value], index) => {
    const comma = index < entries.length - 1 ? ',' : '';
    console.log(`  ${key}: '${value}'${comma}`);
  });

  console.log('};');
  console.log('');
  console.log(`// Total icons: ${Object.keys(iconPaths).length}`);

  if (errors.length > 0) {
    console.error('\n// Errors:');
    errors.forEach(err => console.error(`// - ${err}`));
  }
}

// List available icons if --list flag is passed
if (process.argv.includes('--list')) {
  try {
    const files = readdirSync(ICONS_DIR)
      .filter(f => f.endsWith('.svg'))
      .map(f => f.replace('.svg', ''))
      .sort();
    console.log('Available icons in @phosphor-icons/core (regular weight):');
    console.log(files.join('\n'));
  } catch (err) {
    console.error('Failed to list icons:', err.message);
  }
} else {
  main();
}